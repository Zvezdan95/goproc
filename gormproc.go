// ProcedureMeta holds the metadata for a compiled stored procedure, generated by the gormproc CLI.
type ProcedureMeta struct {
	BaseName    string
	Hash        string
	FullName    string
	PostgresSQL string
	MySQLSQL    string
}

// AutoMigrate applies the given procedure definitions to the active database dialect.
func AutoMigrate(db *gorm.DB, procs ...ProcedureMeta) error {
	dialect := db.Dialector.Name()

	// Ensure the metadata table exists
	createTableSQL := `
		CREATE TABLE IF NOT EXISTS gorm_procedure_registry (
			base_name VARCHAR(128) NOT NULL,
			hash VARCHAR(8) NOT NULL,
			full_name VARCHAR(137) NOT NULL PRIMARY KEY,
			dialect VARCHAR(32) NOT NULL,
			created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
		);
	`
	if dialect == "postgres" {
		createTableSQL = `
			CREATE TABLE IF NOT EXISTS gorm_procedure_registry (
				base_name VARCHAR(128) NOT NULL,
				hash VARCHAR(8) NOT NULL,
				full_name VARCHAR(137) NOT NULL PRIMARY KEY,
				dialect VARCHAR(32) NOT NULL,
				created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
			);
		`
	}
	err := db.Exec(createTableSQL).Error
	if err != nil {
		return fmt.Errorf("failed to create procedure registry table: %w", err)
	}

	for _, proc := range procs {
		var existingCount int64
		if err := db.Table("gorm_procedure_registry").Where("full_name = ?", proc.FullName).Count(&existingCount).Error; err != nil {
			return fmt.Errorf("failed to check procedure registry for %s: %w", proc.FullName, err)
		}

		if existingCount > 0 {
			// Already migrated this exact version
			continue
		}

		var stmt string
		if dialect == "postgres" {
			stmt = proc.PostgresSQL
		} else if dialect == "mysql" {
			stmt = proc.MySQLSQL
		} else if dialect == "sqlite" {
			// SQLite does not support stored procedures.
			// Record migration in registry so in-memory tests proceed cleanly.
			if err := db.Exec("INSERT INTO gorm_procedure_registry (base_name, hash, full_name, dialect) VALUES (?, ?, ?, ?)", proc.BaseName, proc.Hash, proc.FullName, dialect).Error; err != nil {
				return fmt.Errorf("failed to update registry for %s: %w", proc.FullName, err)
			}
			continue
		} else {
			return fmt.Errorf("unsupported dialect for gormproc: %s", dialect)
		}

		if stmt == "" {
			return fmt.Errorf("missing SQL statement for dialect %s in procedure %s", dialect, proc.BaseName)
		}

		if dialect == "mysql" {
			// MySQL DDL (CREATE/DROP PROCEDURE) causes an implicit commit in the storage engine.
			// Executing non-transactionally avoids implicit transaction commit errors.
			_ = db.Exec(fmt.Sprintf("DROP PROCEDURE IF EXISTS %s", proc.FullName))
			if err := db.Exec(stmt).Error; err != nil {
				return fmt.Errorf("failed to execute CREATE PROCEDURE for %s: %w", proc.FullName, err)
			}
			if err := db.Exec("INSERT INTO gorm_procedure_registry (base_name, hash, full_name, dialect) VALUES (?, ?, ?, ?)", proc.BaseName, proc.Hash, proc.FullName, dialect).Error; err != nil {
				return fmt.Errorf("failed to update registry for %s: %w", proc.FullName, err)
			}
		} else {
			err = db.Transaction(func(tx *gorm.DB) error {
				if dialect == "postgres" {
					if strings.Contains(strings.ToUpper(stmt), "CREATE OR REPLACE FUNCTION") {
						_ = tx.Exec(fmt.Sprintf("DROP FUNCTION IF EXISTS %s CASCADE", proc.FullName))
					} else {
						_ = tx.Exec(fmt.Sprintf("DROP PROCEDURE IF EXISTS %s CASCADE", proc.FullName))
					}
				}
				if err := tx.Exec(stmt).Error; err != nil {
					return fmt.Errorf("failed to execute CREATE PROCEDURE for %s: %w", proc.FullName, err)
				}

				// Record the migration
				if err := tx.Exec("INSERT INTO gorm_procedure_registry (base_name, hash, full_name, dialect) VALUES (?, ?, ?, ?)", proc.BaseName, proc.Hash, proc.FullName, dialect).Error; err != nil {
					return fmt.Errorf("failed to update registry for %s: %w", proc.FullName, err)
				}
				return nil
			})
			if err != nil {
				return err
			}
		}
	}

	return nil
}

