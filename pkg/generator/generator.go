package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"go/printer"
	"go/token"
	"strings"

	"github.com/user/gormproc/pkg/parser"
)

type GeneratedProc struct {
	Proc     *parser.Procedure
	Hash     string
	PgSQL    string
	MySQLSQL string
}

func printType(fset *token.FileSet, node interface{}) string {
	var buf bytes.Buffer
	printer.Fprint(&buf, fset, node)
	return buf.String()
}

// GenerateCode writes the gen/procedures.go file contents.
func GenerateCode(pkgPath string, procs []GeneratedProc) ([]byte, error) {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by gormproc. DO NOT EDIT.\n")
	buf.WriteString("package gen\n\n")
	
	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t\"gorm.io/gorm\"\n")
	buf.WriteString(fmt.Sprintf("\t\"%s\"\n", pkgPath))
	buf.WriteString("\t\"github.com/user/gormproc\"\n")
	buf.WriteString(")\n\n")

	// Pre-extract signatures to build interface
	buf.WriteString("type Procedures interface {\n")
	for _, p := range procs {
		fset := p.Proc.Pkg.Fset
		funcSig := printType(fset, p.Proc.Func.Type)
		funcSig = strings.TrimPrefix(funcSig, "func")
		
		funcSig = strings.ReplaceAll(funcSig, "BillingResult", "procedures.BillingResult")
		funcSig = strings.ReplaceAll(funcSig, "UserStatusResult", "procedures.UserStatusResult")
		funcSig = strings.ReplaceAll(funcSig, "OptionalData", "procedures.OptionalData")
		
		buf.WriteString(fmt.Sprintf("\t%s%s\n", p.Proc.Name, funcSig))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("type gormProcedures struct {\n\tdb *gorm.DB\n}\n\n")
	
	buf.WriteString("func NewProcedures(db *gorm.DB) Procedures {\n\treturn &gormProcedures{db: db}\n}\n\n")

	for _, p := range procs {
		funcName := fmt.Sprintf("%s_%s", strings.ToLower(p.Proc.Name), p.Hash)
		fset := p.Proc.Pkg.Fset
		
		funcSig := printType(fset, p.Proc.Func.Type)
		funcSig = strings.TrimPrefix(funcSig, "func")
		
		funcSig = strings.ReplaceAll(funcSig, "BillingResult", "procedures.BillingResult")
		funcSig = strings.ReplaceAll(funcSig, "UserStatusResult", "procedures.UserStatusResult")
		funcSig = strings.ReplaceAll(funcSig, "OptionalData", "procedures.OptionalData")

		buf.WriteString(fmt.Sprintf("func (p *gormProcedures) %s%s {\n", p.Proc.Name, funcSig))
		
		// Setup vars
		buf.WriteString("\tvar result ")
		// Determine result type (naive MVP logic for single result + error)
		resType := ""
		if p.Proc.Func.Type.Results != nil && len(p.Proc.Func.Type.Results.List) > 0 {
			resType = printType(fset, p.Proc.Func.Type.Results.List[0].Type)
			resType = strings.ReplaceAll(resType, "BillingResult", "procedures.BillingResult")
			resType = strings.ReplaceAll(resType, "UserStatusResult", "procedures.UserStatusResult")
			resType = strings.ReplaceAll(resType, "OptionalData", "procedures.OptionalData")
		}
		
		buf.WriteString(resType)
		buf.WriteString("\n")
		
		// Build the argument list for Raw("CALL ...")
		var argNames []string
		for _, field := range p.Proc.Func.Type.Params.List {
			for _, name := range field.Names {
				if name.Name != "ctx" {
					argNames = append(argNames, name.Name)
				}
			}
		}
		
		callArgs := strings.Join(argNames, ", ")
		qMarks := make([]string, len(argNames))
		for i := range qMarks {
			qMarks[i] = "?"
		}
		
		if len(argNames) > 0 {
			buf.WriteString(fmt.Sprintf("\terr := p.db.WithContext(ctx).Raw(\"CALL %s(%s)\", %s).Scan(&result).Error\n", funcName, strings.Join(qMarks, ", "), callArgs))
		} else {
			buf.WriteString(fmt.Sprintf("\terr := p.db.WithContext(ctx).Raw(\"CALL %s()\").Scan(&result).Error\n", funcName))
		}
		
		buf.WriteString("\treturn result, err\n")
		buf.WriteString("}\n\n")
	}

	buf.WriteString("var RegisteredProcedures = []gormproc.ProcedureMeta{\n")
	for _, p := range procs {
		baseName := strings.ToLower(p.Proc.Name)
		fullName := fmt.Sprintf("%s_%s", baseName, p.Hash)
		buf.WriteString("\t{\n")
		buf.WriteString(fmt.Sprintf("\t\tBaseName: \"%s\",\n", baseName))
		buf.WriteString(fmt.Sprintf("\t\tHash: \"%s\",\n", p.Hash))
		buf.WriteString(fmt.Sprintf("\t\tFullName: \"%s\",\n", fullName))
		buf.WriteString(fmt.Sprintf("\t\tPostgresSQL: `%s`,\n", p.PgSQL))
		buf.WriteString(fmt.Sprintf("\t\tMySQLSQL: `%s`,\n", p.MySQLSQL))
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Printf("Format error:\n%s\n", buf.String())
		return buf.Bytes(), err
	}
	return formatted, nil
}
