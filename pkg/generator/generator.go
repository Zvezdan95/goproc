package generator

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/printer"
	"go/token"
	"path/filepath"
	"strings"

	"github.com/user/gormproc/pkg/parser"
)

type GeneratedProc struct {
	Proc     *parser.Procedure
	Hash     string
	PgSQL    string
	MySQLSQL string
}

func printType(fset *token.FileSet, node interface{}) string {
	var buf bytes.Buffer
	printer.Fprint(&buf, fset, node)
	return buf.String()
}

func qualifyType(fset *token.FileSet, expr ast.Expr, pkgName string) string {
	primitives := map[string]bool{
		"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
		"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true,
		"float32": true, "float64": true, "string": true, "bool": true,
		"byte": true, "rune": true, "error": true, "any": true,
	}
	switch e := expr.(type) {
	case *ast.Ident:
		if primitives[e.Name] {
			return e.Name
		}
		return pkgName + "." + e.Name
	case *ast.StarExpr:
		return "*" + qualifyType(fset, e.X, pkgName)
	default:
		return printType(fset, e)
	}
}

func buildFuncSig(fset *token.FileSet, funcType *ast.FuncType, pkgName string) (string, []string) {
	var params []string
	if funcType.Params != nil {
		for _, field := range funcType.Params.List {
			typeStr := qualifyType(fset, field.Type, pkgName)
			for _, name := range field.Names {
				params = append(params, fmt.Sprintf("%s %s", name.Name, typeStr))
			}
		}
	}

	var results []string
	if funcType.Results != nil {
		for _, field := range funcType.Results.List {
			results = append(results, qualifyType(fset, field.Type, pkgName))
		}
	}

	resStr := ""
	if len(results) == 1 {
		resStr = " " + results[0]
	} else if len(results) > 1 {
		resStr = fmt.Sprintf(" (%s)", strings.Join(results, ", "))
	}

	return fmt.Sprintf("(%s)%s", strings.Join(params, ", "), resStr), results
}

// GenerateCode writes the gen/procedures.go file contents.
func GenerateCode(pkgPath string, procs []GeneratedProc) ([]byte, error) {
	var buf bytes.Buffer
	pkgName := filepath.Base(pkgPath)

	buf.WriteString("// Code generated by gormproc. DO NOT EDIT.\n")
	buf.WriteString("package gen\n\n")

	buf.WriteString("import (\n")
	buf.WriteString("\t\"context\"\n")
	buf.WriteString("\t_ \"embed\"\n")
	buf.WriteString("\t\"gorm.io/gorm\"\n")
	buf.WriteString(fmt.Sprintf("\t\"%s\"\n", pkgPath))
	buf.WriteString("\t\"github.com/user/gormproc\"\n")
	buf.WriteString(")\n\n")

	// Pre-extract signatures to build interface
	buf.WriteString("type Procedures interface {\n")
	for _, p := range procs {
		fset := p.Proc.Pkg.Fset
		funcSig, _ := buildFuncSig(fset, p.Proc.Func.Type, pkgName)
		buf.WriteString(fmt.Sprintf("\t%s%s\n", p.Proc.Name, funcSig))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("type gormProcedures struct {\n\tdb *gorm.DB\n}\n\n")
	buf.WriteString("func NewProcedures(db *gorm.DB) Procedures {\n\treturn &gormProcedures{db: db}\n}\n\n")

	for _, p := range procs {
		funcName := fmt.Sprintf("%s_%s", strings.ToLower(p.Proc.Name), p.Hash)
		fset := p.Proc.Pkg.Fset
		funcSig, results := buildFuncSig(fset, p.Proc.Func.Type, pkgName)

		buf.WriteString(fmt.Sprintf("func (p *gormProcedures) %s%s {\n", p.Proc.Name, funcSig))

		// Build the argument list for CALL ...
		var argNames []string
		for _, field := range p.Proc.Func.Type.Params.List {
			for _, name := range field.Names {
				if name.Name != "ctx" {
					argNames = append(argNames, name.Name)
				}
			}
		}

		callArgs := strings.Join(argNames, ", ")
		qMarks := make([]string, len(argNames))
		for i := range qMarks {
			qMarks[i] = "?"
		}
		qMarksStr := strings.Join(qMarks, ", ")

		callStmt := ""
		if len(argNames) > 0 {
			callStmt = fmt.Sprintf("\"CALL %s(%s)\", %s", funcName, qMarksStr, callArgs)
		} else {
			callStmt = fmt.Sprintf("\"CALL %s()\"", funcName)
		}

		if len(results) == 1 && results[0] == "error" {
			buf.WriteString(fmt.Sprintf("\terr := p.db.WithContext(ctx).Exec(%s).Error\n", callStmt))
			buf.WriteString("\treturn err\n")
		} else if len(results) == 2 && results[len(results)-1] == "error" {
			resType := results[0]
			buf.WriteString(fmt.Sprintf("\tvar result %s\n", resType))
			buf.WriteString(fmt.Sprintf("\terr := p.db.WithContext(ctx).Raw(%s).Scan(&result).Error\n", callStmt))
			buf.WriteString("\treturn result, err\n")
		} else if len(results) > 2 && results[len(results)-1] == "error" {
			var varNames []string
			for i := 0; i < len(results)-1; i++ {
				vName := fmt.Sprintf("result%d", i+1)
				buf.WriteString(fmt.Sprintf("\tvar %s %s\n", vName, results[i]))
				varNames = append(varNames, vName)
			}
			buf.WriteString(fmt.Sprintf("\trows, err := p.db.WithContext(ctx).Raw(%s).Rows()\n", callStmt))
			buf.WriteString(fmt.Sprintf("\tif err != nil {\n\t\treturn %s, err\n\t}\n", strings.Join(varNames, ", ")))
			buf.WriteString("\tdefer rows.Close()\n")
			buf.WriteString(fmt.Sprintf("\terr = p.db.ScanRows(rows, &%s)\n", varNames[0]))
			for i := 1; i < len(varNames); i++ {
				buf.WriteString("\tif rows.NextResultSet() {\n")
				buf.WriteString(fmt.Sprintf("\t\t_ = p.db.ScanRows(rows, &%s)\n", varNames[i]))
				buf.WriteString("\t}\n")
			}
			buf.WriteString(fmt.Sprintf("\treturn %s, err\n", strings.Join(varNames, ", ")))
		} else {
			buf.WriteString(fmt.Sprintf("\terr := p.db.WithContext(ctx).Exec(%s).Error\n", callStmt))
			buf.WriteString("\treturn err\n")
		}
		buf.WriteString("}\n\n")
	}

	for _, p := range procs {
		baseName := strings.ToLower(p.Proc.Name)
		fullName := fmt.Sprintf("%s_%s", baseName, p.Hash)
		buf.WriteString(fmt.Sprintf("//go:embed %s.postgres.sql\n", fullName))
		buf.WriteString(fmt.Sprintf("var sql_%s_pg string\n\n", fullName))
		buf.WriteString(fmt.Sprintf("//go:embed %s.mysql.sql\n", fullName))
		buf.WriteString(fmt.Sprintf("var sql_%s_my string\n\n", fullName))
	}

	buf.WriteString("var RegisteredProcedures = []gormproc.ProcedureMeta{\n")
	for _, p := range procs {
		baseName := strings.ToLower(p.Proc.Name)
		fullName := fmt.Sprintf("%s_%s", baseName, p.Hash)
		buf.WriteString("\t{\n")
		buf.WriteString(fmt.Sprintf("\t\tBaseName: \"%s\",\n", baseName))
		buf.WriteString(fmt.Sprintf("\t\tHash: \"%s\",\n", p.Hash))
		buf.WriteString(fmt.Sprintf("\t\tFullName: \"%s\",\n", fullName))
		buf.WriteString(fmt.Sprintf("\t\tPostgresSQL: sql_%s_pg,\n", fullName))
		buf.WriteString(fmt.Sprintf("\t\tMySQLSQL: sql_%s_my,\n", fullName))
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Printf("Format error:\n%s\n", buf.String())
		return buf.Bytes(), err
	}
	return formatted, nil
}
